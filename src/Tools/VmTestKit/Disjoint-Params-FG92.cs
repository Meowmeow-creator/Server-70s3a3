using System;using System.IO;using System.Text;using System.Collections.Generic;
// Per-item inputs for command 28 (Norton's disassembler), reconstructed from the reference
// implementation instead of the old 1310-entry whitelist.
//
//   DisJoint::GetResult (ItemUpgradeVtableB2/GetResult.inc) reads only the item script:
//     GetSellPrice()   = CEquipItem +0x30 <- script +0x24 <- .equ [value]   (fallback [price])
//     get_rarity()     = script +0x0c <- .equ [rarity]
//     get_grade()      = script +0x04 <- .equ [grade]
//   _checkDisjointableItem rejects before the formula runs:
//     IsImpossibleDisjoint() = CItem +0x86 <- script +0x6f6 <- [impossible contents] `disjoint` -> 0x13
//     GetAttachType() == 2   <- [attach type] `[trade delete]`                                    -> 0x11
//
// data/disjoint-params-FG92.dat is generated by local-run/pvf/gen_disjoint_params.py; that
// generator refuses to write unless the legacy Disjoint-Catalog-FG92 rows still re-derive
// bit-identically, so this table cannot drift away from the proven 1310-row baseline.
class Offline70DisjointParamsFG92 {
 internal const string Magic="FG92DP01";internal const int MaximumRows=100000;internal const long MaximumBytes=8388608;
 internal const byte ImpossibleDisjoint=1,TradeDelete=2;
 internal sealed class Params{internal byte Rarity,Grade,Flags;internal uint Value;}
 internal static readonly Dictionary<uint,Params> All=new Dictionary<uint,Params>();
 internal static bool Loaded;
 internal static void Load(string path){
  if(Loaded)return;byte[] bytes=File.ReadAllBytes(path);
  if(bytes.Length<76||bytes.Length>MaximumBytes)throw new InvalidDataException("Disjoint params size");
  if(Encoding.ASCII.GetString(bytes,0,8)!=Magic)throw new InvalidDataException("Disjoint params magic");
  string sha=Encoding.ASCII.GetString(bytes,8,64);
  if(!String.Equals(sha,Offline70QuestCatalogFG.CurrentPvf,StringComparison.OrdinalIgnoreCase))throw new InvalidDataException("Disjoint params PVF");
  using(BinaryReader r=new BinaryReader(new MemoryStream(bytes,false),Encoding.ASCII)){
   r.BaseStream.Position=72;int count=r.ReadInt32();
   if(count<0||count>MaximumRows)throw new InvalidDataException("Disjoint params rows");
   if(r.BaseStream.Length!=76L+11L*count)throw new InvalidDataException("Disjoint params trailing bytes");
   for(int i=0;i<count;i++){
    uint id=r.ReadUInt32(),value=r.ReadUInt32();byte rarity=r.ReadByte(),grade=r.ReadByte(),flags=r.ReadByte();
    if(rarity>5||(flags&~(ImpossibleDisjoint|TradeDelete))!=0)throw new InvalidDataException("Disjoint params row bounds");
    if(All.ContainsKey(id))throw new InvalidDataException("Disjoint params duplicate");
    All.Add(id,new Params{Rarity=rarity,Grade=grade,Flags=flags,Value=value});
   }
   Loaded=true;
  }
 }
 internal static Params Get(uint itemId){Params p;return All.TryGetValue(itemId,out p)?p:null;}
}
