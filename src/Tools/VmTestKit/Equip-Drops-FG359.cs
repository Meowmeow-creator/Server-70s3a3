using System;using System.IO;using System.Text;using System.Collections.Generic;
// FG359: the ordinary-dungeon equipment drops that were never wired.
//
// Sources (reference/rednf/remake/source/DNFServer/GameServer/Game):
//   CMonsterDrop (0x08536da8 generateRandomItem -> 0x08535ed2 _generateRandomItem):
//     one roll per item type (1..4); type 2 = any gear, type 4 = creature gear. Each roll is
//     probability[bracket] * dungeonBonus[type][difficulty] * monsterTypeBonus[type][kind] *
//     partyBonus[type][0] out of 10000, then CLuckPoint::GetItemRarity(m_rarityBasis[type]) and
//     CItemGenRateTable::chooseItem(type, rarity, mob level).
//   CSpecialMonsterDrop (0x08536882 _generateRandomItem): the same 4-type loop over
//     etc/itemdropinfo_monseter_extra.etc, but its pools contain ONLY [special monster drop]
//     items filtered by [difficulty for extra drop] / [dungeon type for extra drop]; it runs
//     before the ordinary loop and is skipped when field40 (hell groups all killed) is set.
// Both pools are CItemGenRateTable/CSecialIMonsterDropItemGenRateTable::generateTable products:
// [grade] window from [item drop ref table], rarity / creation rate / item-type filters, and
// random-option items are KEPT (the normal script also passes keepRandomOption=true).
//
// data/equip-drops-FG359.dat is generated by local-run/pvf/gen_equip_drops.py.
class Offline70EquipCatalogFG359{
 internal const string Magic="FG359ED1";internal const int MaximumBytes=8388608;
 internal sealed class DropTable{
  internal ushort[][] Prob;            // [bracket][7] = lo, hi, gold, type1..type4
  internal float[][] DiffBonus;        // [5][5] = drop type 0..4 x difficulty 0..4
  internal float[][] MonsterBonus;     // [5][4] = drop type x monster kind
  internal float[][] PartyBonus;       // [5][4] = drop type x party index
  internal int[][] Rarity;             // [5][6], row 0 unused (types are 1..4)
  internal byte[] WindowMin,WindowMax;
 }
 internal sealed class Pool{internal uint[] Cumulative,Items;}
 internal static DropTable Normal,Special;
 internal static Dictionary<int,Pool> Pool2=new Dictionary<int,Pool>();   // key=(rarity<<8)|level
 internal static Dictionary<int,Pool> Pool4=new Dictionary<int,Pool>();
 internal static Dictionary<int,Pool> SpecialPools=new Dictionary<int,Pool>(); // (difficulty<<24)|(type<<16)|(rarity<<8)|level
 internal static int NormalRows,SpecialRows;
 internal static bool Loaded;

 internal static int PoolKey(int rarity,int level){return (rarity<<8)|level;}
 internal static int SpecialKey(int difficulty,int type,int rarity,int level){return (difficulty<<24)|(type<<16)|(rarity<<8)|level;}
 internal static Pool GenericPool(int type,int rarity,int level){Pool p;return (type==2?Pool2:Pool4).TryGetValue(PoolKey(rarity,level),out p)?p:null;}
 internal static Pool SpecialPool(int difficulty,int type,int rarity,int level){Pool p;return SpecialPools.TryGetValue(SpecialKey(difficulty,type,rarity,level),out p)?p:null;}

 internal static void Load(string path){
  if(Loaded)return;byte[] bytes=File.ReadAllBytes(path);
  if(bytes.Length<74||bytes.Length>MaximumBytes)throw new InvalidDataException("Equip catalog size");
  if(Encoding.ASCII.GetString(bytes,0,8)!=Magic)throw new InvalidDataException("Equip catalog magic");
  string sha=Encoding.ASCII.GetString(bytes,8,64);
  if(!String.Equals(sha,Offline70QuestCatalogFG.CurrentPvf,StringComparison.OrdinalIgnoreCase))throw new InvalidDataException("Equip catalog PVF");
  using(BinaryReader r=new BinaryReader(new MemoryStream(bytes,false),Encoding.ASCII)){
   r.BaseStream.Position=72;
   Normal=ReadTable(r);Pool2=ReadPool(r,2);Pool4=ReadPool(r,4);
   Special=ReadTable(r);SpecialPools=ReadSpecialPool(r);
   if(r.BaseStream.Position!=r.BaseStream.Length)throw new InvalidDataException("Equip catalog trailing bytes");
   NormalRows=CountRows(Pool2)+CountRows(Pool4);SpecialRows=CountRows(SpecialPools);Loaded=true;
  }
 }
 static int CountRows(Dictionary<int,Pool> pools){int rows=0;foreach(Pool p in pools.Values)rows+=p.Items.Length;return rows;}
 static DropTable ReadTable(BinaryReader r){
  DropTable t=new DropTable();
  int probs=r.ReadByte();if(probs<1||probs>16)throw new InvalidDataException("Equip probability count");
  t.Prob=new ushort[probs][];
  for(int i=0;i<probs;i++){t.Prob[i]=new ushort[7];for(int k=0;k<7;k++)t.Prob[i][k]=r.ReadUInt16();if(t.Prob[i][1]<t.Prob[i][0]||t.Prob[i][1]>255||t.Prob[i][0]<1)throw new InvalidDataException("Equip probability row");}
  t.DiffBonus=ReadFloats(r,5,5,"difficulty bonus");
  t.MonsterBonus=ReadFloats(r,5,4,"monster bonus");
  t.PartyBonus=ReadFloats(r,5,4,"party bonus");
  int rarityRows=r.ReadByte();if(rarityRows!=4)throw new InvalidDataException("Equip rarity row count");
  t.Rarity=new int[5][];t.Rarity[0]=new int[6];
  for(int i=1;i<=4;i++){int[] row=new int[6];for(int k=0;k<6;k++)row[k]=r.ReadInt32();if(row[0]<=0||row[5]<=row[1])throw new InvalidDataException("Equip rarity row");t.Rarity[i]=row;}
  int levels=r.ReadByte();if(levels<1||levels>200)throw new InvalidDataException("Equip level window count");
  t.WindowMin=new byte[levels];t.WindowMax=new byte[levels];
  for(int i=0;i<levels;i++){t.WindowMin[i]=r.ReadByte();t.WindowMax[i]=r.ReadByte();if(t.WindowMax[i]>200)throw new InvalidDataException("Equip level window");}
  return t;
 }
 static float[][] ReadFloats(BinaryReader r,int rows,int columns,string what){
  int n=r.ReadByte();if(n!=rows)throw new InvalidDataException("Equip "+what+" rows");
  float[][] result=new float[rows][];
  for(int i=0;i<rows;i++){result[i]=new float[columns];for(int k=0;k<columns;k++){result[i][k]=r.ReadSingle();if(result[i][k]<0||result[i][k]>1000)throw new InvalidDataException("Equip "+what+" value");}}
  return result;
 }
 static Dictionary<int,Pool> ReadPool(BinaryReader r,int type){
  int count=r.ReadInt32();if(count<0||count>4096)throw new InvalidDataException("Equip pool table count");
  Dictionary<int,Pool> pools=new Dictionary<int,Pool>(count);
  for(int i=0;i<count;i++){
   int rarity=r.ReadByte(),level=r.ReadByte(),rows=r.ReadUInt16();
   if(rarity>5||level<1||level>200||rows==0||rows>4096)throw new InvalidDataException("Equip pool bounds");
   Pool p=ReadRows(r,rows);int key=PoolKey(rarity,level);
   if(pools.ContainsKey(key))throw new InvalidDataException("Equip pool duplicate");
   pools.Add(key,p);
  }
  return pools;
 }
 static Dictionary<int,Pool> ReadSpecialPool(BinaryReader r){
  int count=r.ReadInt32();if(count<0||count>16384)throw new InvalidDataException("Equip special table count");
  Dictionary<int,Pool> pools=new Dictionary<int,Pool>(count);
  for(int i=0;i<count;i++){
   int difficulty=r.ReadByte(),type=r.ReadByte(),rarity=r.ReadByte(),level=r.ReadByte(),rows=r.ReadUInt16();
   if(difficulty>4||type<1||type>4||rarity>5||level<1||level>200||rows==0||rows>4096)throw new InvalidDataException("Equip special pool bounds");
   Pool p=ReadRows(r,rows);int key=SpecialKey(difficulty,type,rarity,level);
   if(pools.ContainsKey(key))throw new InvalidDataException("Equip special pool duplicate");
   pools.Add(key,p);
  }
  return pools;
 }
 static Pool ReadRows(BinaryReader r,int rows){
  Pool p=new Pool();p.Cumulative=new uint[rows];p.Items=new uint[rows];uint previous=0;
  for(int i=0;i<rows;i++){uint cumulative=r.ReadUInt32(),item=r.ReadUInt32();if(cumulative<=previous||item<3)throw new InvalidDataException("Equip pool row");p.Cumulative[i]=cumulative;p.Items[i]=item;previous=cumulative;}
  return p;
 }
}

class Offline70EquipDropsFG359{
 static readonly HashSet<uint> KnownItems=new HashSet<uint>(),MissingItems=new HashSet<uint>();
 internal static bool Registered(uint item){
  if(KnownItems.Contains(item))return true;if(MissingItems.Contains(item))return false;
  try{Offline70Economy.Definition(item);KnownItems.Add(item);return true;}catch(InvalidDataException){MissingItems.Add(item);return false;}
 }
 internal static int Bracket(Offline70EquipCatalogFG359.DropTable table,int level){
  for(int i=0;i<table.Prob.Length;i++)if(level>=table.Prob[i][0]&&level<=table.Prob[i][1])return i;
  return -1;
 }
 // (int)(probability * difficulty bonus * monster-kind bonus * party bonus): the native script
 // stores f32 rates and truncates once after the x87 product, so keep the float values rather
 // than re-deriving them (e.g. 60 * 1.4f = 83.999998 -> 83).
 internal static int Threshold(Offline70EquipCatalogFG359.DropTable table,int bracket,int type,byte difficulty,byte kind){
  return (int)((double)table.Prob[bracket][2+type]*table.DiffBonus[type][difficulty]*table.MonsterBonus[type][kind]*table.PartyBonus[type][0]);
 }
 internal static int GetItemRarity(int[] table,int roll){for(int i=0;i<=5;i++)if(roll<=table[i])return i;return 0;}
 internal static uint Choose(Offline70EquipCatalogFG359.Pool pool,uint draw){
  int low=0,high=pool.Cumulative.Length-1;
  while(low<high){int middle=(low+high)/2;if(pool.Cumulative[middle]>=draw)high=middle;else low=middle+1;}
  return pool.Cumulative[low]>=draw?pool.Items[low]:0;
 }
 // Native order: the special table runs first (only when the kill did not finish a hell group),
 // then one roll per ordinary type. `kind` is the converted monster role (0..3).
 internal static void Append(List<Offline70FloorDropsFG119.Reward> rewards,int mobLevel,int standardLevel,byte difficulty,byte kind,string receipt,bool specialEnabled,Func<string,uint,uint> draw){
  if(rewards==null||draw==null)return;
  if(Offline70EquipCatalogFG359.Special!=null&&specialEnabled){
   int bracket=Bracket(Offline70EquipCatalogFG359.Special,standardLevel);
   if(bracket>=0)for(int type=1;type<=4;type++){
    if(rewards.Count>=Offline70FloorDropsFG119.MaximumRows)return;
    string prefix="equip359:special"+type;
    if((int)draw(prefix+":chance",10000)>Threshold(Offline70EquipCatalogFG359.Special,bracket,type,difficulty,kind))continue;
    int rarity=GetItemRarity(Offline70EquipCatalogFG359.Special.Rarity[type],(int)(1+draw(prefix+":rarity",1000000)));
    Offline70EquipCatalogFG359.Pool pool=Offline70EquipCatalogFG359.SpecialPool(difficulty,type,rarity,mobLevel);
    if(pool==null)continue;
    uint item=Choose(pool,draw(prefix+":item",pool.Cumulative[pool.Cumulative.Length-1]));
    if(item==0||!Registered(item))continue;
    rewards.Add(new Offline70FloorDropsFG119.Reward{Item=item,Quantity=1,Source="equip-special359"});
   }
  }
  if(Offline70EquipCatalogFG359.Normal==null)return;
  int normalBracket=Bracket(Offline70EquipCatalogFG359.Normal,standardLevel);
  if(normalBracket<0)return;
  foreach(int type in new int[]{2,4}){
   if(rewards.Count>=Offline70FloorDropsFG119.MaximumRows)return;
   string prefix="equip359:t"+type;
   if((int)draw(prefix+":chance",10000)>Threshold(Offline70EquipCatalogFG359.Normal,normalBracket,type,difficulty,kind))continue;
   int rarity=GetItemRarity(Offline70EquipCatalogFG359.Normal.Rarity[type],(int)(1+draw(prefix+":rarity",1000000)));
   Offline70EquipCatalogFG359.Pool pool=Offline70EquipCatalogFG359.GenericPool(type,rarity,mobLevel);
   if(pool==null)continue;
   uint item=Choose(pool,draw(prefix+":item",pool.Cumulative[pool.Cumulative.Length-1]));
   if(item==0||!Registered(item))continue;
   rewards.Add(new Offline70FloorDropsFG119.Reward{Item=item,Quantity=1,Source=type==2?"equip-generic359":"equip-creature359"});
  }
 }
 internal static void Append(List<Offline70FloorDropsFG119.Reward> rewards,int mobLevel,int standardLevel,byte difficulty,byte kind,string receipt,bool specialEnabled){
  Append(rewards,mobLevel,standardLevel,difficulty,kind,receipt,specialEnabled,
   delegate(string purpose,uint maximum){return Offline70ClearItemsFG125.Draw(receipt,purpose,maximum);});
 }
}
